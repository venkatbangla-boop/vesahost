/* APP-08 local-only portable-copy and atomic store validation, synthetic data. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const base=path.resolve(__dirname,'..');const memory=new Map();
const localStorage={getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const env={module:{exports:{}},JSON,Math,Date,localStorage};env.globalThis=env;vm.createContext(env);
const load=p=>vm.runInContext(fs.readFileSync(path.join(base,p),'utf8'),env,{filename:p});
for(const f of ['src/domain/vendor-profile.js','src/domain/certification-evidence.js','src/domain/capability-matcher.js','src/data/saved-copy-codec.js','src/data/local-record-port.js'])load(f);
const E=env.VesaFactoryVendorProfile,C=env.VesaFactoryVendorCopyCodec,S=env.VesaFactoryVendorLocalStore;
const a=new S('synthetic-A@vesa.local'),b=new S('synthetic-B@vesa.local');
assert(a.key.startsWith('vesa.factory-vendor.records.v1.'));assert.notEqual(a.key,b.key);
let p=E.create({vendorName:'SYN VENDOR',country:'BD',sourceRef:'SYN REVIEWED REGISTER'});p.mode='local';
assert.equal(a.save(p),p.id);assert.equal(a.list().length,1);assert.equal(b.list().length,0,'User-scoped storage required');
let site={id:'SYN-SITE',siteName:'SYN APPAREL FACTORY',country:'BD',process:'woven shirts',sourceRef:'SYN SOURCE DOCUMENT'};
p=E.append(p,'site',site);a.save(p);assert.equal(a.load(p.id).sites.length,1);
const copy=C.encode(p),parsed=JSON.parse(copy);assert.equal(parsed.format,'VESA-FACTORY-VENDOR-COPY-1');
const restored=C.decode(copy);assert.equal(restored.id,p.id);assert.equal(restored.sites[0].siteName,site.siteName);
const snapshot=localStorage.getItem(a.key);
assert.throws(()=>C.decode(copy.replace('SYN VENDOR','ALTERED VENDOR')),/altered\/unsupported/);
assert.throws(()=>C.decode('{this is not JSON'),/unreadable/);
assert.throws(()=>C.decode('x'.repeat(C.maxLength+1)),/safe limit/);
const spoof=JSON.parse(copy);spoof.record.status='BSCI FULLY APPROVED';spoof.hash=C.hash(JSON.stringify(spoof.record));
assert.throws(()=>C.decode(JSON.stringify(spoof)),/cannot claim certification/);
const older=E.create({vendorName:'SYN VENDOR',country:'BD',sourceRef:'SYN REVIEWED REGISTER'});older.id=p.id;older.mode='local';
assert.throws(()=>a.save(older),/Older vendor evidence/);
const invalid=E.clone(p);invalid.sites.push({...site,id:'SYN-DUP'});
assert.throws(()=>a.save(invalid),/Duplicate factory site/);
assert.equal(localStorage.getItem(a.key),snapshot,'Invalid copied/older/duplicate record must not alter storage');
const second=E.clone(restored);second.id=E.id('FVD-COPY');second.audit.push({revision:second.revision,at:new Date().toISOString(),action:'Copy recovered separately'});
a.save(second);assert.equal(a.list().length,2);assert.equal(b.list().length,0);
const now=localStorage.getItem(a.key);memory.set(a.key,'{bad-storage');
assert.throws(()=>a.read(),/Existing vendor data damaged/);
assert.equal(localStorage.getItem(a.key),'{bad-storage');memory.set(a.key,now);
const revised=E.append(p,'review',{id:'REVIEW-01',siteId:'SYN-SITE',reviewer:'SYN REVIEWER',checklistRef:'SYN CHECKLIST',sourceRef:'SYN INTERNAL REPORT',reviewDate:'2026-10-17',internalOutcome:'needs-information'});
a.save(revised);assert.equal(a.load(p.id).revision,revised.revision);
assert.equal(a.load(p.id).reviews[0].internalOutcome,'needs-information');
console.log('FACTORY VENDOR M2 LOCAL COPY PASS: private per-user key, save/reload, older-revision refusal, corrupt/oversized/forged/duplicate atomicity, separate copy restore.');
